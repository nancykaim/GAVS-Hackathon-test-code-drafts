def norm(s): return (s or "").strip().lower()

import difflib
ALIASES = {"rani":["रानी"], "gauri":["गौरी","gouri"], "lakshmi":["लक्ष्मी"],
           "ganga":["गंगा"], "kali":["काली","kaali"]}
def name_ok(got, exp):
    got = norm(got)
    if exp is None: return got in ("", "null", "none")
    forms = [exp] + ALIASES.get(exp, [])
    return any(got == f or difflib.SequenceMatcher(None, got, f).ratio() >= 0.8 for f in forms)

