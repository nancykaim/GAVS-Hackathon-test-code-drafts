def parse(text):
    m = re.search(r"\{.*\}", text, re.S)
    if not m: return {"_parse_error": text}
    s = re.sub(r'(?<=[{,\n])\s*\.?"?(\w+)"?\s*:', r' "\1":', m.group(0))
    try:
        d = json.loads(s)
    except Exception:
        return {"_parse_error": text}
    for k, v in d.items():
        if isinstance(v, str) and v.strip().lower() in ("null", "none", ""):
            d[k] = None
    if not d.get("intent"): d["intent"] = "other"
    return d

def extract(msg):
    chat = [{"role": "system", "content": SYSTEM}, {"role": "user", "content": msg}]
    prompt = tok.apply_chat_template(chat, tokenize=False, add_generation_prompt=True)
    inputs = tok(prompt, return_tensors="pt").to(model.device)
    out = model.generate(**inputs, max_new_tokens=150, do_sample=False)
    text = tok.decode(out[0][inputs["input_ids"].shape[1]:], skip_special_tokens=True)
    return parse(text)

def ground(d, msg):
    n = d.get("animal_name")
    if n and n.strip().lower() not in msg.lower():
        d["_name_rejected"] = n
        d["animal_name"] = None
    return d

