from pydub import AudioSegment

def to_chunks(path, chunk_s=CHUNK_SECONDS):
    audio = AudioSegment.from_file(path).set_frame_rate(16000).set_channels(1)
    base = os.path.splitext(os.path.basename(path))[0]
    os.makedirs("/content/chunks", exist_ok=True)
    step = chunk_s * 1000
    out_files = []
    for i, start in enumerate(range(0, len(audio), step)):
        seg = audio[start:start + step]
        if len(seg) < 500:
            continue
        out = f"/content/chunks/{base}_{i:03d}.wav"
        seg.export(out, format="wav")
        out_files.append(out)
    return out_files, len(audio) / 1000.0

