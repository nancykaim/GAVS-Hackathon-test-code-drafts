RANK = {"WATCH": 0, "NEED MORE INFO": 1, "SAME-DAY": 2, "URGENT": 3}
LLM_MAP = {"none": None, "watch": "WATCH", "same-day": "SAME-DAY", "urgent": "URGENT"}

def higher(a, b):
    if a is None: return b
    if b is None: return a
    return a if RANK[a] >= RANK[b] else b

def real_symptoms(data):
    s = data.get("symptoms") or []
    return [x for x in s if str(x).strip().lower() not in ("not mentioned", "unclear", "")]

def triage(data, transcript):
    if "error" in data:
        return "NEED MORE INFO", ["extraction failed"]
    blob = " ".join([
        transcript.lower(),
        str(data.get("english_translation", "")).lower(),
        " ".join(map(str, real_symptoms(data))).lower(),
    ])
    level, reasons = None, []
    for lvl, groups in RED_FLAGS.items():
        for reason, kws in groups.items():
            if any(k in blob for k in kws):
                reasons.append(f"{lvl}: {reason}")
                level = higher(level, lvl)
    llm = LLM_MAP.get(str(data.get("llm_concern_level", "none")).lower())
    if llm:
        level = higher(level, llm)       # the AI model can only raise the level
        reasons.append(f"model concern: {llm}")
    if level is None:
        level = "WATCH" if real_symptoms(data) else "NEED MORE INFO"
    return level, reasons

